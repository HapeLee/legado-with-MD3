"""Build a CPU-only, reduced-kernel ORT for the pinned SMaLL-100 ONNX models.

Requires onnx, onnxruntime==1.31.1, numpy and flatbuffers in Python.
Source checkout: microsoft/onnxruntime v1.31.1 with cmake/external/onnx initialized.
Keeps the upstream Java API and licenses; builds the matching CPU runtime and JNI bridge.
"""

import argparse
import collections
import hashlib
import json
import os
from pathlib import Path
import re
import subprocess
import sys
import zipfile

VERSION = "1.31.1"
COMMIT = "6af1a932e2286d5c58166085d24c68783033edee"
ONNX_COMMIT = "2bb50465112feca9003e1ed654d77f01ff1415ca"
BASE_AAR_SHA256 = "d4d50660300ed2c4f38ffdfd5ab5bfa3a22f995f282dda24f42ea3ea55467b49"
ROOT = Path(__file__).resolve().parents[2]
CATALOG = ROOT / "app/src/main/assets/models/small100-models.json"


def sha256(path):
    with path.open("rb") as stream:
        return hashlib.file_digest(stream, "sha256").hexdigest()


def run(command, **kwargs):
    print(subprocess.list2cmdline([str(arg) for arg in command]), flush=True)
    subprocess.run([str(arg) for arg in command], check=True, **kwargs)


def collect(graph, versions, operators):
    import onnx

    for node in graph.node:
        domain = node.domain or "ai.onnx"
        operators[(domain, versions[domain])].add(node.op_type)
        for attribute in node.attribute:
            if attribute.type == onnx.AttributeProto.GRAPH:
                collect(attribute.g, versions, operators)
            elif attribute.type == onnx.AttributeProto.GRAPHS:
                for subgraph in attribute.graphs:
                    collect(subgraph, versions, operators)


def prepare(args):
    import onnx
    import onnxruntime as ort

    if ort.__version__ != VERSION:
        raise RuntimeError(f"Configuration must be generated with onnxruntime=={VERSION}")
    operators = collections.defaultdict(set)
    specs = json.loads(CATALOG.read_text(encoding="utf-8"))["models"]
    for spec in specs:
        if not spec["name"].endswith(".onnx"):
            continue
        model = args.models / spec["name"]
        if not model.exists():
            alias = "encoder.onnx" if spec["name"].startswith("encoder") else "decoder.onnx"
            model = args.models / alias
        if model.stat().st_size != spec["size"] or sha256(model) != spec["sha256"]:
            raise RuntimeError(f"Pinned model verification failed: {model}")

        def include(path):
            graph = onnx.load(str(path))
            versions = {entry.domain or "ai.onnx": entry.version for entry in graph.opset_import}
            collect(graph.graph, versions, operators)

        include(model)
        # Include original kernels AND all CPU optimization levels, including both If branches.
        # BASIC/EXTENDED/ALL may emit different fused operators. Only collecting top-level
        # nodes or only the unoptimized graph would break the merged decoder or quantization.
        for level in (ort.GraphOptimizationLevel.ORT_ENABLE_BASIC,
                      ort.GraphOptimizationLevel.ORT_ENABLE_EXTENDED,
                      ort.GraphOptimizationLevel.ORT_ENABLE_ALL):
            optimized = args.build_dir / f"{model.stem}-{level.name}.onnx"
            options = ort.SessionOptions()
            options.log_severity_level = 3
            options.intra_op_num_threads = 2
            options.graph_optimization_level = level
            options.optimized_model_filepath = str(optimized)
            session = ort.InferenceSession(str(model), options, providers=["CPUExecutionProvider"])
            del session
            try:
                include(optimized)
            finally:
                optimized.unlink(missing_ok=True)
    content = (
        "# SMaLL-100 INT8 d66e226; ORT 1.31.1 CPU; original + BASIC/EXTENDED/ALL graphs.\n"
        "# Generated by tools/small100/build_runtime.py; includes nested merged-decoder branches.\n"
        + "".join(f"{domain};{version};{','.join(sorted(names))}\n"
                  for (domain, version), names in sorted(operators.items()))
    )
    (args.build_dir / "required-operators.config").write_text(content, encoding="utf-8")
    print(content, flush=True)


def build(args):
    actual = subprocess.check_output(["git", "rev-parse", "HEAD"], cwd=args.source, text=True).strip()
    if actual != COMMIT:
        raise RuntimeError(f"Expected ORT {COMMIT}, got {actual}")
    onnx_source = args.source / "cmake/external/onnx"
    actual_onnx = subprocess.check_output(["git", "rev-parse", "HEAD"], cwd=onnx_source, text=True).strip()
    if actual_onnx != ONNX_COMMIT:
        raise RuntimeError(f"Expected ONNX {ONNX_COMMIT}, got {actual_onnx}")
    checked_config = ROOT / "tools/small100/required-operators.config"
    if checked_config.read_text() != (args.build_dir / "required-operators.config").read_text():
        raise RuntimeError("Generated operators differ from the reviewed configuration")
    environment = os.environ.copy()
    environment["PATH"] = os.pathsep.join((str(args.ninja.parent), str(args.cmake.parent), environment["PATH"]))
    run([
        sys.executable, args.source / "tools/ci_build/build.py",
        "--build_dir", args.build_dir / "android", "--config", "MinSizeRel",
        "--android", "--android_abi", "arm64-v8a", "--android_api", "26",
        "--android_sdk_path", args.android_sdk, "--android_ndk_path", args.android_ndk,
        "--cmake_generator", "Ninja", "--cmake_path", args.cmake,
        "--skip_submodule_sync", "--skip_pip_install", "--skip_tests",
        "--build_shared_lib", "--disable_ml_ops", "--disable_generation_ops", "--disable_rtti",
        "--no_telemetry", "--enable_lto",
        "--include_ops_by_config", args.build_dir / "required-operators.config",
        "--parallel", args.jobs, "--target", "onnxruntime",
        "--cmake_extra_defines", f"CMAKE_MAKE_PROGRAM={args.ninja.as_posix()}",
        f"FETCHCONTENT_SOURCE_DIR_ONNX={onnx_source.as_posix()}",
        "CMAKE_SHARED_LINKER_FLAGS=-Wl,-z,max-page-size=16384",
    ], cwd=args.source, env=environment)


def package(args):
    library = args.build_dir / "android/MinSizeRel/libonnxruntime.so"
    if not library.is_file():
        raise RuntimeError(f"Missing compiled runtime: {library}")
    if sha256(args.base_aar) != BASE_AAR_SHA256:
        raise RuntimeError("Upstream Java/JNI AAR checksum mismatch")
    with library.open("rb") as stream:
        header = stream.read(20)
    if header[:6] != b"\x7fELF\x02\x01" or int.from_bytes(header[18:20], "little") != 183:
        raise RuntimeError("Expected an Android arm64 ELF library")
    strip_name = "llvm-strip.exe" if os.name == "nt" else "llvm-strip"
    strip = next((args.android_ndk / "toolchains/llvm/prebuilt").glob(f"*/bin/{strip_name}"))
    stripped = args.build_dir / "libonnxruntime-stripped.so"
    run([strip, "--strip-unneeded", "-o", stripped, library])
    library = stripped
    # The upstream Android JNI bridge links NNAPI symbols. Build it from the same
    # release without USE_NNAPI so the reduced CPU library can be loaded on Android.
    jni_dir = args.build_dir / "jni"
    headers = jni_dir / "headers"
    classes = jni_dir / "classes"
    headers.mkdir(parents=True, exist_ok=True)
    classes.mkdir(parents=True, exist_ok=True)
    java_root = args.source / "java/src/main"
    javac_name = "javac.exe" if os.name == "nt" else "javac"
    javac = Path(os.environ["JAVA_HOME"]) / "bin" / javac_name
    run([javac, "--release", "8", "-Xlint:-options", "-h", headers, "-d", classes,
         *sorted((java_root / "java/ai/onnxruntime").rglob("*.java")),
         java_root / "android/ai/onnxruntime/platform/Fp16Conversions.java"])
    clang = strip.with_name("clang.exe" if os.name == "nt" else "clang")
    jni = jni_dir / "libonnxruntime4j_jni.so"
    run([clang, "--target=aarch64-linux-android26", "-shared", "-std=c11", "-Oz",
         "-fPIC", "-fvisibility=hidden", "-fstack-protector-strong",
         "-Wl,--no-undefined", "-Wl,-soname,libonnxruntime4j_jni.so", "-Wl,-z,max-page-size=16384",
         "-I", args.source / "include", "-I", headers,
         "-I", args.source / "include/onnxruntime/core/session",
         "-I", args.build_dir / "android/MinSizeRel",
         "-I", args.source / "orttraining/orttraining/training_api/include",
         *sorted((java_root / "native").glob("*.c")),
         "-L", args.build_dir / "android/MinSizeRel", "-lonnxruntime", "-lm", "-ldl", "-o", jni])
    run([strip, "--strip-unneeded", jni])
    nm = strip.with_name("llvm-nm.exe" if os.name == "nt" else "llvm-nm")

    def symbols(path, option):
        listing = subprocess.check_output([str(nm), "--dynamic", option, str(path)], text=True)
        return {line.split()[-1].split("@")[0] for line in listing.splitlines() if line.split()}

    declared = set()
    for header in headers.glob("*.h"):
        declared.update(re.findall(r"\b(Java_\w+)\s*\(", header.read_text()))
    exported = symbols(jni, "--defined-only")
    if missing := declared - exported:
        raise RuntimeError(f"JNI methods missing from bridge: {sorted(missing)}")
    required = {name for name in symbols(jni, "--undefined-only") if name.startswith("Ort")}
    if missing := required - symbols(library, "--defined-only"):
        raise RuntimeError(f"Runtime exports required by JNI are missing: {sorted(missing)}")
    readelf = strip.with_name("llvm-readelf.exe" if os.name == "nt" else "llvm-readelf")
    for payload in (library, jni):
        listing = subprocess.check_output([str(readelf), "--program-headers", "--wide", str(payload)], text=True)
        alignments = [int(line.split()[-1], 16) for line in listing.splitlines()
                      if line.split() and line.split()[0] == "LOAD"]
        if not alignments or any(alignment < 16384 for alignment in alignments):
            raise RuntimeError(f"Native library is not 16 KiB aligned: {payload}")
    args.output.parent.mkdir(parents=True, exist_ok=True)
    temporary = args.output.with_suffix(".aar.tmp")
    with zipfile.ZipFile(args.base_aar) as original, zipfile.ZipFile(
            temporary, "w", compression=zipfile.ZIP_DEFLATED, compresslevel=9) as output:
        for entry in original.infolist():
            if entry.is_dir():
                continue
            if entry.filename.startswith("jni/"):
                # Manga translation is arm64-only, as enforced before native initialization.
                if entry.filename == "jni/arm64-v8a/libonnxruntime.so":
                    output.write(library, entry.filename)
                elif entry.filename == "jni/arm64-v8a/libonnxruntime4j_jni.so":
                    output.write(jni, entry.filename)
            elif not entry.filename.startswith("prefab/"):
                output.writestr(entry.filename, original.read(entry.filename))
        output.write(args.source / "LICENSE", "assets/onnxruntime/LICENSE.txt")
        output.write(args.source / "ThirdPartyNotices.txt", "assets/onnxruntime/ThirdPartyNotices.txt")
    temporary.replace(args.output)
    checksum = sha256(args.output)
    args.output.with_suffix(".aar.sha256").write_text(f"{checksum}  {args.output.name}\n", encoding="ascii")
    report = {
        "version": VERSION, "source": "https://github.com/microsoft/onnxruntime",
        "commit": COMMIT, "onnx_commit": ONNX_COMMIT,
        "abi": "arm64-v8a", "api": 26, "configuration": "MinSizeRel",
        "cpu_only": True, "onnx_format": True, "lto": True,
        "disabled": ["unused operator kernels", "traditional ML", "generation operators", "RTTI", "telemetry"],
        "base_aar_sha256": sha256(args.base_aar), "runtime_sha256": sha256(library),
        "runtime_bytes": library.stat().st_size, "aar_sha256": checksum,
        "jni_sha256": sha256(jni), "jni_bytes": jni.stat().st_size,
        "verified_jni_methods": len(declared), "jni_runtime_imports": sorted(required),
        "operators_sha256": sha256(args.build_dir / "required-operators.config"),
    }
    args.output.with_suffix(".json").write_text(json.dumps(report, indent=2) + "\n", encoding="utf-8")
    print(json.dumps(report, indent=2), flush=True)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--phase", choices=("prepare", "build", "package", "all"), default="all")
    for name in ("source", "build-dir", "models", "android-sdk", "android-ndk", "cmake", "ninja", "base-aar"):
        parser.add_argument(f"--{name}", required=True, type=Path)
    parser.add_argument("--output", type=Path,
                        default=ROOT / f"app/libs/onnxruntime-small100-{VERSION}.aar")
    parser.add_argument("--jobs", type=int, default=4)
    args = parser.parse_args()
    args.build_dir.mkdir(parents=True, exist_ok=True)
    for name, operation in (("prepare", prepare), ("build", build), ("package", package)):
        if args.phase in (name, "all"):
            operation(args)


if __name__ == "__main__":
    main()
