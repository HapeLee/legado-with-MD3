"""Generate the Android 26-28 upright lookup from the pinned Unicode 17 UCD file."""
import argparse
import hashlib
from pathlib import Path

URL = "https://www.unicode.org/Public/17.0.0/ucd/VerticalOrientation.txt"
SHA256 = "dcef09c3fb24d356b042569c328ec341efc5b53447700d799f2fb4834c3cd3cd"


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("source", type=Path, help="Downloaded VerticalOrientation-17.0.0.txt")
    parser.add_argument("output", type=Path, help="MangaUnicodeVertical.kt destination")
    args = parser.parse_args()
    raw = args.source.read_bytes()
    assert hashlib.sha256(raw).hexdigest() == SHA256, "Unicode data SHA-256 mismatch"
    assert raw.startswith(b"# VerticalOrientation-17.0.0.txt")
    ranges = []
    for line in raw.decode("utf-8").splitlines():
        fields = line.split("#")[0].strip().split(";")
        if len(fields) != 2 or fields[1].strip() not in ("U", "Tu"):
            continue
        code = fields[0].strip().split("..")
        ranges.append((int(code[0], 16), int(code[-1], 16)))
    merged = []
    for start, end in sorted(ranges):
        if merged and start <= merged[-1][1] + 1:
            merged[-1] = (merged[-1][0], max(end, merged[-1][1]))
        else:
            merged.append((start, end))
    body = "\n".join("        " + ", ".join(f"0x{a:x}, 0x{b:x}" for a, b in merged[i:i+5]) + ","
                     for i in range(0, len(merged), 5))
    digest = hashlib.sha256(raw).hexdigest()
    source = """package io.legado.app.data.repository.manga

// Unicode VerticalOrientation-17.0.0 U/Tu ranges. Generated by tools/manga-layout/generate_vertical_orientation.py.
// Data copyright © 2025 Unicode, Inc. License: assets/licenses/UNICODE-LICENSE-V3.txt
// Source: SOURCE_URL
// Source SHA-256: SOURCE_SHA
internal object MangaUnicodeVertical {
    private val uprightRanges = intArrayOf(
TABLE
    )
    fun upright(codePoint: Int): Boolean {
        var low = 0; var high = uprightRanges.size / 2 - 1
        while (low <= high) {
            val middle = (low + high) ushr 1
            val start = uprightRanges[middle * 2]; val end = uprightRanges[middle * 2 + 1]
            when {
                codePoint < start -> high = middle - 1
                codePoint > end -> low = middle + 1
                else -> return true
            }
        }
        return false
    }
}
"""
    args.output.write_text(source.replace("SOURCE_URL", URL).replace("SOURCE_SHA", digest).replace("TABLE", body), encoding="utf-8")
    print(f"{len(merged)} upright ranges; SHA-256 {digest}")


if __name__ == "__main__":
    main()
